use crate::manifest::*;
use serde::Serialize;
use std::{fmt::Write, fs, path::Path};

#[derive(Serialize)]
struct GeneratedManifest<'a> {
    schema_version: u32,
    project: &'a str,
    runtime_dylib: &'a str,
    hooks: Vec<GeneratedPatch<'a>>,
    objective_c_hooks: Vec<GeneratedObjectiveHook<'a>>,
}
#[derive(Serialize)]
struct GeneratedPatch<'a> {
    name: &'a str,
    enabled: bool,
    module: &'a Option<String>,
    signature: &'a Option<String>,
    original_slot: Option<u32>,
    failure_behavior: FailureBehavior,
}
#[derive(Serialize)]
struct GeneratedObjectiveHook<'a> {
    name: &'a str,
    class: &'a str,
    selector: &'a str,
    class_method: bool,
    signature: &'a str,
    replacement: &'a str,
    preserve_original: bool,
}

fn ident(value: &str) -> String {
    value
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect()
}

fn c_escape(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
}
fn callback_declaration(signature: &str, symbol: &str) -> anyhow::Result<String> {
    let open = signature
        .find('(')
        .ok_or_else(|| anyhow::anyhow!("invalid callback signature"))?;
    Ok(format!(
        "extern \"C\" {} {}{};",
        signature[..open].trim(),
        symbol,
        &signature[open..]
    ))
}

pub fn generate(m: &Manifest, manifest_path: &Path) -> anyhow::Result<()> {
    let dir = manifest_path.parent().unwrap_or(Path::new("."));
    let out = dir.join("generated");
    fs::create_dir_all(&out)?;

    let mut c = String::from("// Generated by iaot. DO NOT EDIT.\n#pragma once\n#include <IAOT/IAOT.hpp>\n#include <cstdint>\n\n");
    writeln!(c, "enum class IAOTFlag : std::uint32_t {{")?;
    for x in &m.config.flags {
        writeln!(c, "    {} = {},", ident(&x.name), x.index)?;
    }
    writeln!(c, "}};")?;
    writeln!(c, "enum class IAOTString : std::uint32_t {{")?;
    for x in &m.config.strings {
        writeln!(c, "    {} = {},", ident(&x.name), x.index)?;
    }
    writeln!(c, "}};")?;
    writeln!(c, "enum class IAOTCallback : std::uint32_t {{")?;
    for x in &m.config.callbacks {
        writeln!(c, "    {} = {},", ident(&x.name), x.index)?;
    }
    writeln!(c, "}};")?;
    for x in &m.config.flags {
        writeln!(
            c,
            "inline constexpr bool IAOTDefaultFlag_{} = {};",
            ident(&x.name),
            x.default
        )?;
    }
    for x in &m.config.strings {
        writeln!(
            c,
            "inline constexpr const char* IAOTDefaultString_{} = OBF(\"{}\");",
            ident(&x.name),
            c_escape(&x.default)
        )?;
    }
    for x in &m.config.callbacks {
        writeln!(
            c,
            "inline constexpr const char* IAOTCallbackSymbol_{} = OBF(\"{}\");",
            ident(&x.name),
            c_escape(&x.symbol)
        )?;
    }
    c.push_str("inline bool IAOTGetFlag(IAOTFlag v){return iaot::GetBool(static_cast<std::uint32_t>(v));}\ninline void IAOTSetFlag(IAOTFlag v,bool x){iaot::SetBool(static_cast<std::uint32_t>(v),x);}\ninline const char* IAOTGetString(IAOTString v){return iaot::GetString(static_cast<std::uint32_t>(v));}\ninline void IAOTSetString(IAOTString v,const char* x){iaot::SetString(static_cast<std::uint32_t>(v),x);}\ninline std::uintptr_t IAOTGetCallback(IAOTCallback v){return iaot::GetCallback(static_cast<std::uint32_t>(v));}\ninline void IAOTSetCallback(IAOTCallback v,std::uintptr_t x){iaot::SetCallback(static_cast<std::uint32_t>(v),x);}\n");
    fs::write(out.join("IAOTGeneratedConfig.hpp"), c)?;

    let mut f = String::from(
        "// Generated by iaot. DO NOT EDIT.\n#pragma once\n#include <IAOT/IAOT.hpp>\n#include <string>\nnamespace iaot::generated {\n",
    );
    for x in &m.functions {
        if x.kind.as_deref() == Some("objc") {
            continue;
        }
        let sig = x.signature.as_ref().unwrap();
        let a = x.address.as_ref().unwrap();
        match a.kind.as_str() {
            "vmaddr" => writeln!(
                f,
                "inline auto {}(){{return iaot::AppFunction<{}>::FromVmAddr(0x{:X}ULL);}}",
                x.name,
                sig,
                a.value.unwrap_or(0)
            )?,
            "rva" => writeln!(
                f,
                "inline auto {}(){{return iaot::AppFunction<{}>::FromRva(0x{:X}ULL);}}",
                x.name,
                sig,
                a.value.unwrap_or(0)
            )?,
            "runtime" => writeln!(
                f,
                "inline auto {}(){{return iaot::AppFunction<{}>::FromRuntime(0x{:X}ULL);}}",
                x.name,
                sig,
                a.value.unwrap_or(0)
            )?,
            "symbol" => writeln!(
                f,
                "inline auto {}(){{return iaot::AppFunction<{}>::FromSymbol(OBF(\"{}\"));}}",
                x.name,
                sig,
                c_escape(a.symbol.as_deref().unwrap_or(""))
            )?,
            _ => anyhow::bail!("unsupported function address type {}", a.kind),
        }
    }
    writeln!(f, "}}")?;
    if m.functions
        .iter()
        .any(|function| function.kind.as_deref() == Some("objc"))
    {
        writeln!(f, "#if defined(__OBJC__)")?;
        for function in m
            .functions
            .iter()
            .filter(|function| function.kind.as_deref() == Some("objc"))
        {
            writeln!(
                f,
                "{}",
                callback_declaration(
                    function.signature.as_deref().unwrap(),
                    function.replacement.as_deref().unwrap(),
                )?
            )?;
        }
        writeln!(f, "namespace iaot::generated {{")?;
        for function in m
            .functions
            .iter()
            .filter(|function| function.kind.as_deref() == Some("objc"))
        {
            let name = ident(&function.name);
            writeln!(
                f,
                "inline IMP& OriginalIMP_{name}(){{static IMP value=nullptr;return value;}}"
            )?;
            writeln!(
                f,
                "inline auto Original_{name}(){{return iaot::AppFunction<{}>::FromRuntime(reinterpret_cast<std::uintptr_t>(OriginalIMP_{name}()));}}",
                function.signature.as_deref().unwrap()
            )?;
            writeln!(
                f,
                "inline bool Install_{name}(){{return iaot::Replace{}Method(OBF(\"{}\"),OBF(\"{}\"),reinterpret_cast<IMP>(&{}),{});}}",
                if function.class_method { "Class" } else { "Instance" },
                c_escape(function.class_name.as_deref().unwrap()),
                c_escape(function.selector.as_deref().unwrap()),
                function.replacement.as_deref().unwrap(),
                if function.preserve_original {
                    format!("&OriginalIMP_{name}()")
                } else {
                    "nullptr".into()
                }
            )?;
        }
        writeln!(f, "}}")?;
        writeln!(f, "#endif")?;
    }
    fs::write(out.join("IAOTGeneratedFunctions.hpp"), f)?;

    let mut originals = String::from("// Generated by iaot. DO NOT EDIT.\n#pragma once\n#include <IAOT/IAOT.hpp>\nnamespace iaot::generated {\n");
    for patch in m
        .patches
        .iter()
        .filter(|patch| patch.original_slot.is_some())
    {
        writeln!(
            originals,
            "inline auto Original_{}(){{return iaot::OriginalFunction<{}>({});}}",
            ident(&patch.name),
            patch.signature.as_deref().unwrap(),
            patch.original_slot.unwrap()
        )?;
    }
    writeln!(originals, "}}")?;
    fs::write(out.join("IAOTGeneratedOriginals.hpp"), originals)?;

    let il2cpp_module = m.analysis.il2cpp_module.as_deref().unwrap_or("");
    let overlay_enabled = m.build.menu && m.analysis.rendering_backend != "disabled";
    let log_level = match m.build.log_level.as_str() {
        "debug" => "Debug",
        "info" => "Info",
        "warning" => "Warning",
        "error" => "Error",
        "off" => "Off",
        _ => unreachable!("manifest validation rejects unknown log levels"),
    };
    let project = format!("// Generated by iaot. DO NOT EDIT.\n#pragma once\n#define IAOT_PROJECT_NAME \"{}\"\n#define IAOT_ENABLE_MENU {}\n#define IAOT_ENABLE_PERSISTENCE {}\n#define IAOT_ENABLE_IL2CPP_RUNTIME {}\n#define IAOT_IL2CPP_MODULE \"{}\"\n#define IAOT_RENDERING_BACKEND_{} 1\n",
        c_escape(&m.project.name), u8::from(overlay_enabled), u8::from(m.build.persistence),
        u8::from(m.analysis.runtime_il2cpp), c_escape(il2cpp_module),
        ident(&m.analysis.rendering_backend).to_ascii_uppercase());
    fs::write(out.join("IAOTGeneratedProject.hpp"), project)?;
    fs::write(
        out.join("IAOTGeneratedProject.mk"),
        format!(
            "# Generated by iaot. DO NOT EDIT.\nIAOT_BUILD_MODE := {}\nIAOT_ENABLE_OVERLAY := {}\nIAOT_OVERLAY_BACKEND := {}\n",
            m.build.mode,
            u8::from(overlay_enabled),
            if overlay_enabled { "metal" } else { "auto" }
        ),
    )?;

    let mut h = String::from("// Generated by iaot. DO NOT EDIT.\n#include <IAOT/IAOT.hpp>\n#include \"IAOTGeneratedConfig.hpp\"\n#include \"IAOTGeneratedFunctions.hpp\"\n#include \"IAOTGeneratedOriginals.hpp\"\n#include \"IAOTGeneratedProject.hpp\"\n");
    for callback in m
        .config
        .callbacks
        .iter()
        .filter(|callback| callback.auto_register)
    {
        writeln!(
            h,
            "{}",
            callback_declaration(callback.signature.as_deref().unwrap(), &callback.symbol)?
        )?;
    }
    for x in &m.generated_hooks {
        writeln!(
            h,
            "extern \"C\" bool {}(const iaot::HookContext& ctx);",
            x.symbol
        )?;
    }
    writeln!(h, "namespace iaot {{ void RegisterGeneratedHooks() {{")?;
    writeln!(h, "    SetLogLevel(LogLevel::{log_level});")?;
    if m.analysis.runtime_il2cpp {
        writeln!(h, "    RegisterHook({{ OBF(\"IL2CPPRuntimeResolver\"), +[](const HookContext&) -> bool {{ il2cpp::Options options; options.moduleName = *IAOT_IL2CPP_MODULE ? IAOT_IL2CPP_MODULE : nullptr; return il2cpp::InitializeAsync(options); }} }});")?;
    } else {
        writeln!(h, "    il2cpp::MarkNotApplicable();")?;
    }
    if m.config
        .callbacks
        .iter()
        .any(|callback| callback.auto_register)
    {
        writeln!(
            h,
            "    RegisterHook({{ OBF(\"GeneratedCallbacks\"), +[](const HookContext&) -> bool {{"
        )?;
        for callback in m
            .config
            .callbacks
            .iter()
            .filter(|callback| callback.auto_register)
        {
            writeln!(
                h,
                "        IAOTSetCallback(IAOTCallback::{}, reinterpret_cast<std::uintptr_t>(&{}));",
                ident(&callback.name),
                callback.symbol
            )?;
        }
        writeln!(h, "        return true; }} }});")?;
    }
    for function in m
        .functions
        .iter()
        .filter(|function| function.kind.as_deref() == Some("objc"))
    {
        writeln!(
            h,
            "    RegisterHook({{ OBF(\"ObjectiveC::{}\"), +[](const HookContext&) -> bool {{ return generated::Install_{}(); }} }});",
            c_escape(&function.name),
            ident(&function.name)
        )?;
    }
    for x in &m.generated_hooks {
        writeln!(
            h,
            "    RegisterHook({{ OBF(\"{}\"), {} }});",
            c_escape(&x.name),
            x.symbol
        )?;
    }
    writeln!(h, "}} }}")?;
    fs::write(out.join("IAOTGeneratedHooks.mm"), h)?;

    let hook_manifest = GeneratedManifest {
        schema_version: 1,
        project: &m.project.name,
        runtime_dylib: &m.runtime.dylib_name,
        hooks: m
            .patches
            .iter()
            .map(|patch| GeneratedPatch {
                name: &patch.name,
                enabled: patch.enabled,
                module: &patch.module,
                signature: &patch.signature,
                original_slot: patch.original_slot,
                failure_behavior: patch.failure_behavior,
            })
            .collect(),
        objective_c_hooks: m
            .functions
            .iter()
            .filter(|function| function.kind.as_deref() == Some("objc"))
            .map(|function| GeneratedObjectiveHook {
                name: &function.name,
                class: function.class_name.as_deref().unwrap(),
                selector: function.selector.as_deref().unwrap(),
                class_method: function.class_method,
                signature: function.signature.as_deref().unwrap(),
                replacement: function.replacement.as_deref().unwrap(),
                preserve_original: function.preserve_original,
            })
            .collect(),
    };
    fs::write(
        out.join("hook-manifest.yaml"),
        format!(
            "# Generated by iaot. DO NOT EDIT.\n{}",
            serde_yaml::to_string(&hook_manifest)?
        ),
    )?;
    Ok(())
}
